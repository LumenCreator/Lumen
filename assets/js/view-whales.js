/* Lumen Terminal — Flows: large on-chain holders and institutional positioning. */
(function (global) {
  'use strict';
  var L = global.Lumen, U = global.UNIVERSE, W = global.WHALES, UIx = global.UI, el = L.el, F = L.F;

  var st = { hours: 24, chain: 'ALL', kind: 'ALL', asset: null, tab: 'onchain' };
  var bodyEl = null;

  function mount(world, params) {
    if (params.asset) st.asset = params.asset;
    var root = el('div', { class: 'whales' });
    root.appendChild(UIx.panel('Flows', {
      icon: '🐋', class: 'p-wtabs',
      actions: [UIx.toggleRow([{ v: 'onchain', n: 'On-chain' }, { v: 'inst', n: 'Institutional' }, { v: 'wallets', n: 'Tracked wallets' }], st.tab,
        function (v) { st.tab = v; render(world); })]
    }, [
      el('div', { class: 'w-filters' }, [
        UIx.toggleRow([{ v: 24, n: '24h' }, { v: 72, n: '3d' }, { v: 168, n: '7d' }, { v: 720, n: '30d' }], st.hours, function (v) { st.hours = +v; render(world); }),
        UIx.toggleRow([{ v: 'ALL', n: 'all chains' }].concat(W.CHAINS.map(function (c) { return { v: c, n: c }; })), st.chain, function (v) { st.chain = v; render(world); }),
        UIx.toggleRow([{ v: 'ALL', n: 'all flows' }, { v: 'inflow', n: 'to exchange' }, { v: 'outflow', n: 'off exchange' }, { v: 'transfer', n: 'wallet↔wallet' }], st.kind,
          function (v) { st.kind = v; render(world); }),
        st.asset ? el('button', { class: 'chip on', text: st.asset + ' ✕', onclick: function () { st.asset = null; render(world); } }) : null
      ])
    ]));
    bodyEl = el('div', { id: 'w-body' });
    root.appendChild(bodyEl);
    setTimeout(function () { render(world); }, 0);
    return root;
  }

  function flows(world) {
    var cutoff = Date.now() - st.hours * 3600e3;
    return world.flows.filter(function (f) {
      if (f.t < cutoff) return false;
      if (st.chain !== 'ALL' && f.chain !== st.chain) return false;
      if (st.kind !== 'ALL' && f.dir !== st.kind) return false;
      if (st.asset && f.asset !== st.asset) return false;
      return true;
    });
  }

  function render(world) {
    var host = bodyEl;
    if (!host) return;
    L.clear(host);
    if (st.tab === 'onchain') renderOnchain(host, world);
    else if (st.tab === 'inst') renderInst(host, world);
    else renderWallets(host, world);
  }

  function renderOnchain(host, world) {
    var fl = flows(world);
    var sum = W.summarise(fl, st.hours);
    var smart = W.smartMoney(fl, st.hours);
    var demo = !global.PROVIDERS.isLive();

    if (demo) {
      host.appendChild(el('div', { class: 'bt-banner tone-sim' }, [
        UIx.badge('SIMULATED', 'sim'),
        el('span', { text: 'These wallets, addresses and transfers are generated by the demo engine. The addresses are deliberately not real. Add an Etherscan key and a proxy in Settings, then switch to LIVE, to track actual addresses.' })
      ]));
    }

    host.appendChild(UIx.panel('Net flow · ' + st.hours + 'h', { icon: '📊', class: 'p-wsum' }, [
      el('div', { class: 'grid4' }, [
        UIx.stat('Net', F.usdc(sum.net), { tone: sum.net >= 0 ? 'up' : 'down', sub: sum.bias }),
        UIx.stat('Into exchanges', F.usdc(sum.inflow), { tone: 'down', sub: 'supply hitting order books' }),
        UIx.stat('Out of exchanges', F.usdc(sum.outflow), { tone: 'up', sub: 'moving to custody' }),
        UIx.stat('Transfers', String(sum.n))
      ]),
      el('div', { class: 'two-col' }, [
        el('div', {}, [el('h4', { text: 'By asset (net)' }),
          UIx.canvasBox('', Math.max(60, sum.byAsset.length * 20 + 8), function (cv) {
            global.CHART.hbars(cv, sum.byAsset, { labelW: 58, fmt: function (v) { return F.usdc(v); } });
          })]),
        el('div', {}, [el('h4', { text: 'By chain (net)' }),
          UIx.canvasBox('', Math.max(60, sum.byChain.length * 20 + 8), function (cv) {
            global.CHART.hbars(cv, sum.byChain, { labelW: 58, fmt: function (v) { return F.usdc(v); } });
          })])
      ]),
      el('p', { class: 'note small', text: 'Read exchange inflows as potential distribution and outflows as accumulation. It is a heuristic: an inflow can equally be a market maker rebalancing inventory, and a single large transfer can swamp a whole day.' })
    ]));

    host.appendChild(UIx.panel('Accumulating and distributing', { icon: '🧭', class: 'p-smart' }, [
      smart.length ? UIx.table([{ t: 'Wallet' }, { t: 'Type' }, { t: 'Chain' }, { t: 'Net', align: 'r' }, { t: 'Txns', align: 'r' }],
        smart.map(function (s) {
          return {
            _class: 'clk', _click: function () { showWallet(s.w, world); },
            cells: [s.w.label, s.w.kindName, s.w.chain,
              { node: el('span', { class: s.net >= 0 ? 'up' : 'down', text: F.usdc(s.net) }), align: 'r' },
              { t: String(s.n), align: 'r' }]
          };
        })) : UIx.empty('No qualifying wallets in this window')
    ]));

    host.appendChild(UIx.panel('Transfer ledger', { icon: '🧾', class: 'p-ledger', count: fl.length }, [
      fl.length ? UIx.table([{ t: 'Time' }, { t: 'Asset' }, { t: 'Size', align: 'r' }, { t: 'From' }, { t: 'To' }, { t: 'Read' }],
        fl.slice(0, 80).map(function (f) {
          return {
            _class: f.dir === 'inflow' ? 'loss' : f.dir === 'outflow' ? 'win' : '',
            _click: function () { showWallet(f.from, world); },
            cells: [new Date(f.t).toISOString().slice(5, 16).replace('T', ' '),
              f.asset, { t: F.usdc(f.usd), align: 'r' },
              f.from.label, f.to.label,
              { node: UIx.badge(f.dir, f.dir === 'inflow' ? 'down' : f.dir === 'outflow' ? 'up' : 'n', f.note) }]
          };
        })) : UIx.empty('No transfers match')
    ]));
  }

  function renderInst(host, world) {
    var rows = world.institutional;
    var bySector = {};
    rows.forEach(function (r) {
      bySector[r.sector] = (bySector[r.sector] || 0) + (r.changePct > 0 ? 1 : -1) * (r.value / 1e8);
    });
    var secList = Object.keys(bySector).map(function (k) {
      var ind = U.findIndustry(k);
      return { k: ind ? ind.n.split(' —')[0] : k, v: bySector[k], color: ind ? ind.color : null };
    }).sort(function (a, b) { return b.v - a.v; });

    if (!global.PROVIDERS.isLive()) {
      host.appendChild(el('div', { class: 'bt-banner tone-sim' }, [
        UIx.badge('SIMULATED', 'sim'),
        el('span', { text: 'Generated 13F-style and insider records. With an FMP key and the proxy configured, LIVE mode pulls real filings.' })
      ]));
    }

    host.appendChild(UIx.panel('Where institutions are moving', { icon: '🏛', class: 'p-inst' }, [
      UIx.canvasBox('', secList.length * 20 + 10, function (cv) {
        global.CHART.hbars(cv, secList, { labelW: 120, fmt: function (v) { return (v >= 0 ? '+' : '') + v.toFixed(1); } });
      }),
      el('p', { class: 'note small', text: 'Net direction of reported position changes weighted by disclosed value. 13F data is filed with a lag of up to 45 days — it tells you where money went, not where it is going.' })
    ]));

    host.appendChild(UIx.panel('Filings', { icon: '🗂', class: 'p-filings', count: rows.length }, [
      UIx.table([{ t: 'As of' }, { t: 'Holder' }, { t: 'Type' }, { t: 'Ticker' }, { t: 'Company' }, { t: 'Change', align: 'r' }, { t: 'Value', align: 'r' }],
        rows.slice(0, 60).map(function (r) {
          return {
            _class: 'clk', _click: function () { global.APP.execute('chart ' + r.t); },
            cells: [F.date(new Date(r.asOf)), r.holder,
              { node: UIx.badge(r.kind, r.kind === 'insider' ? 'warn' : 'n') },
              r.t, r.name,
              { node: el('span', { class: r.changePct >= 0 ? 'up' : 'down', text: F.pct(r.changePct, 0) }), align: 'r' },
              { t: F.usdc(r.value), align: 'r' }]
          };
        }))
    ]));
  }

  function renderWallets(host, world) {
    var ws = world.wallets.filter(function (w) { return st.chain === 'ALL' || w.chain === st.chain; });
    host.appendChild(UIx.panel('Tracked wallets', { icon: '👛', class: 'p-wallets', count: ws.length }, [
      UIx.table([{ t: 'Label' }, { t: 'Type' }, { t: 'Chain' }, { t: 'Asset' }, { t: 'Balance', align: 'r' }, { t: 'Address' }, { t: '', align: 'r' }],
        ws.map(function (w) {
          return {
            _class: 'clk', _click: function () { showWallet(w, world); },
            cells: [w.label, w.kindName, w.chain, w.asset,
              { t: F.usdc(w.bal), align: 'r' },
              { node: el('code', { class: 'addr', text: w.addr.slice(0, 10) + '…' + w.addr.slice(-6) }) },
              { node: w.watch ? UIx.badge('watched', 'up') : el('span', { text: '' }), align: 'r' }]
          };
        }))
    ]));
  }

  function showWallet(w, world) {
    var acts = W.walletActivity(world.flows, w.id).slice(0, 40);
    var net = 0;
    acts.forEach(function (f) { net += f.to.id === w.id ? f.usd : -f.usd; });
    UIx.modal(w.label, [
      el('div', { class: 'sd-head' }, [
        UIx.badge(w.kindName, 'i'), UIx.badge(w.chain, 'n'),
        w.sim ? UIx.badge('SIM', 'sim', 'Generated wallet — the address is not a real address.') : null
      ]),
      el('div', { class: 'grid4' }, [
        UIx.stat('Balance', F.usdc(w.bal)),
        UIx.stat('Primary asset', w.asset),
        UIx.stat('Net (window)', F.usdc(net), { tone: net >= 0 ? 'up' : 'down' }),
        UIx.stat('Transfers', String(acts.length))
      ]),
      el('code', { class: 'addr full', text: w.addr }),
      el('h4', { class: 'sd-sub', text: 'Activity' }),
      acts.length ? UIx.table([{ t: 'Time' }, { t: 'Direction' }, { t: 'Counterparty' }, { t: 'Size', align: 'r' }],
        acts.map(function (f) {
          var out = f.from.id === w.id;
          return [new Date(f.t).toISOString().slice(5, 16).replace('T', ' '),
            { node: UIx.badge(out ? 'sent' : 'received', out ? 'down' : 'up') },
            out ? f.to.label : f.from.label,
            { t: F.usdc(f.usd), align: 'r' }];
        })) : UIx.empty('No activity in the window')
    ], { class: 'wide' });
  }

  UIx.register('whales', { mount: mount });
})(window);
